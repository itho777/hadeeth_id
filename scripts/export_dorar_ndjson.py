"""
export_dorar_ndjson.py — extract the Dorar (al-Durar al-Saniyyah) commentary rows
from the R2 commentary tree into one NDJSON, ready for a dedicated D1 database.

Source trees, both generated by build_offline.py and already shipped to R2:
  export_site/commentaries/<book>.ndjson          anchor-keyed rows (15,224 Dorar)
  export_site/commentaries/matched/<book>.ndjson  hadith-keyed rows (2,368 Dorar)

The two trees carry overlapping but different fields, so the export takes the
union and adds `kind` ('anchor' | 'matched') plus a deterministic `id`. Values
are copied verbatim; nothing is rewritten, normalized or dropped.

Output: export/d1/dorar/dorar_commentary.ndjson

Usage:
  python scripts/export_dorar_ndjson.py            # write the NDJSON
  python scripts/export_dorar_ndjson.py --check    # report only, write nothing
"""
import hashlib
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TREES = [
    ("anchor", os.path.join(ROOT, "export_site", "commentaries")),
    ("matched", os.path.join(ROOT, "export_site", "commentaries", "matched")),
]
OUT = os.path.join(ROOT, "export", "d1", "dorar", "dorar_commentary.ndjson")

SKIP = {"_catalog.ndjson", "editions.ndjson"}
MARKER = re.compile(r"Dorar|الدرر السنية")

# Union of both tree shapes. Order is the column order of the D1 table.
COLUMNS = [
    "id", "kind", "book_id", "anchor_id", "hadith_id", "hadith_number", "source_key",
    "source_name_ar", "source_name_en", "source_name_id",
    "muhaddith", "rawi", "grade", "masdar",
    "hadith_ar", "hadith_en",
    "explanation_ar", "explanation_en",
    "syarah_ar", "syarah_en", "takhrij",
    "langs", "origin",
]


def files(base):
    for name in sorted(os.listdir(base)):
        if not name.endswith(".ndjson"):
            continue
        if name in SKIP or name.endswith("_index.ndjson"):
            continue
        yield os.path.join(base, name)


def main():
    check = "--check" in sys.argv
    rows = []
    seen = set()
    dupes = 0
    for kind, base in TREES:
        if not os.path.isdir(base):
            raise SystemExit(f"missing source tree: {base}")
        for path in files(base):
            for line in open(path, encoding="utf-8"):
                if not line.strip() or not MARKER.search(line):
                    continue
                src = json.loads(line)
                rid = f"{kind}:{src.get('book_id')}:{src.get('anchor_id')}:{src.get('source_key')}"
                if rid in seen:
                    dupes += 1
                    continue
                seen.add(rid)
                row = {c: src.get(c) for c in COLUMNS}
                row["id"] = rid
                row["kind"] = kind
                rows.append(row)

    rows.sort(key=lambda r: (r["kind"], r["book_id"] or "", int(r["anchor_id"] or 0), r["source_key"] or ""))
    size = sum(len(json.dumps(r, ensure_ascii=False).encode()) + 1 for r in rows)
    print(f"rows      : {len(rows):,}")
    print(f"duplicates: {dupes}")
    print(f"bytes     : {size:,} ({size / 1048576:.2f} MiB)")
    for kind, _ in TREES:
        n = sum(1 for r in rows if r["kind"] == kind)
        print(f"  {kind:8s}: {n:,}")
    books = sorted({r["book_id"] for r in rows})
    print(f"books     : {len(books)} -> {' '.join(books)}")

    if check:
        print("check only, nothing written")
        return

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    h = hashlib.sha256()
    with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        for r in rows:
            line = json.dumps(r, ensure_ascii=False) + "\n"
            fh.write(line)
            h.update(line.encode())
    print(f"wrote     : {OUT}")
    print(f"sha256    : {h.hexdigest()}")


if __name__ == "__main__":
    main()
