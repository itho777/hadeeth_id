#!/usr/bin/env python
"""Export the cross-dataset map into the R2 NDJSON mirror.

The map is built in D1 and kept under data/. After the 2026-11-21 corrections
round it was the one large artifact with no key in export_site/_manifest.ndjson,
so the mirror was still the 2026-11-20 snapshot. Copy the artifacts verbatim
and merge their manifest entries by key -- never rebuild the manifest from
the local tree here, because R2 carries objects (e.g. api/ row files) whose
build inputs are no longer on disk and upload() prunes what is not listed.

Also refresh the manifest entries of the commentary files rewritten by
scripts/syarah_build.py, which writes files but no manifest.
"""
import shutil
from pathlib import Path

import site_r2

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "export_site"

# source (relative to repo) -> R2 key. map_raw.ndjson is the 40 MB matching
# scratch file; it is an intermediate, not a result, and is deliberately absent.
FILES = [
    ("data/hadith_map.ndjson", "map/hadith_map.ndjson"),
    ("data/hadith_map_coverage.ndjson", "map/hadith_map_coverage.ndjson"),
    ("data/hadith_map_rejects.ndjson", "map/hadith_map_rejects.ndjson"),
    ("data/hadith_map_delta_2026-11-21.ndjson", "map/hadith_map_delta.ndjson"),
    ("data/hadith_map_retired_2026-11-21.ndjson", "map/hadith_map_retired.ndjson"),
    ("data/shamela_map.ndjson", "map/shamela_map.ndjson"),
    ("data/syarah_ahmad_links.ndjson", "map/syarah_ahmad_links.ndjson"),
    ("data/syarah_ahmad_rejects.ndjson", "map/syarah_ahmad_rejects.ndjson"),
]

# commentary files regenerated by syarah_build.py, whose writer returns a
# manifest slice but does not merge it into the persisted manifest
REFRESH = [
    "commentaries/_catalog.ndjson",
    "commentaries/editions.ndjson",
    "commentaries/matched/ahmad.ndjson",
    "commentaries/matched/ahmad_index.ndjson",
]


def entry(key):
    path = OUT / key
    return {"path": f"export_site/{key}", "key": key,
            "bytes": path.stat().st_size, "ct": "application/x-ndjson"}


def main():
    items = site_r2.load_manifest()
    by_key = {i["key"]: i for i in items}
    before = len(items)

    for src, key in FILES:
        origin = ROOT / src
        if not origin.is_file():
            raise SystemExit(f"missing source: {src}")
        dst = OUT / key
        dst.parent.mkdir(parents=True, exist_ok=True)
        if not dst.exists() or dst.read_bytes() != origin.read_bytes():
            shutil.copyfile(origin, dst)
        by_key[key] = entry(key)

    for key in REFRESH:
        if not (OUT / key).is_file():
            raise SystemExit(f"missing regenerated file: {key}")
        by_key[key] = entry(key)

    merged = [by_key[k] for k in sorted(by_key)]
    with site_r2.MANIFEST.open("w", encoding="utf-8", newline="\n") as f:
        for i in merged:
            f.write(site_r2.json.dumps(i, ensure_ascii=False,
                                       separators=(",", ":")) + "\n")

    print(f"manifest: {before} -> {len(merged)} keys "
          f"(+{len(merged) - before})")
    for key in [k for _, k in FILES] + REFRESH:
        print(f"  {key:46} {by_key[key]['bytes']:>10,}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
